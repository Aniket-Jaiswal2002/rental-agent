"""Regenerate the README's generated blocks from the raw eval files. Nothing in these blocks is typed by hand.

    python -m scripts.fill_readme --headline evals/raw/<headline>.json \
        [--followups evals/raw/<a>.json ...] \
        [--final evals/raw/<final>.json | --final-pending <sha>] \
        [--later evals/raw/<rerun>.json ...] \
        [--limitations 03 ...]

Blocks (each between <!-- NAME:START ... --> and <!-- NAME:END --> markers in README.md):
- EVAL-SUMMARY: one plain-language result sentence for the top of the README.
- EVAL-RESULTS: the same result in plain language, then one table (case | headline | after-fix | full pass |
  later re-runs). Commit ids appear only in the table headers. Per-check rates, "what changed", the
  reasoning_effort footnote and failure details stay in evals/results.md, which the block links to.
- LATENCY: model time per turn from the latest full pass (--final), or from the headline pass without one.

The headline column is always the first full pass. --limitations names cases (by number) that are documented
known limitations; it changes only the wording, never a result.
"""
from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path

from evals.report import UNKNOWN, load_raw, pct

ROOT = Path(__file__).parent.parent
NOT_RUN = "—"
MARK_NOTE = "generated by `python -m scripts.fill_readme` from the raw eval files; do not hand-edit"
START, END = "<!-- EVAL-RESULTS:START", "<!-- EVAL-RESULTS:END -->"  # kept for callers of fill()


def _commits(raws: list[dict]) -> str:
    shas = sorted({(r.get("commit") or UNKNOWN)[:7] for raw in raws for r in raw["results"]})
    return ", ".join(f"`{s}`" for s in shas) or UNKNOWN


def _cell(runs: list[dict]) -> str:
    """Status of each run of one case; the reasoning_effort is named only when the runs differ in it."""
    if not runs:
        return NOT_RUN
    many_efforts = len({r.get("reasoning_effort") for r in runs}) > 1
    return ", ".join(r["status"] + (f" (effort {r.get('reasoning_effort')})" if many_efforts else "") for r in runs)


def _passed(results: list[dict]) -> tuple[int, int]:
    real = [r for r in results if r["status"] != "RATE_LIMITED"]
    return sum(r["status"] == "PASS" for r in real), len(real)


def _num(cases: list[str]) -> str:
    nums = [c[:2] for c in cases]
    return nums[0] if len(nums) == 1 else f"{', '.join(nums[:-1])} and {nums[-1]}"


def _by_case(raws: list[dict], case: str) -> list[dict]:
    return [r for raw in raws for r in raw["results"] if r["case"] == case]


def _ok(raws: list[dict], case: str) -> bool:
    runs = _by_case(raws, case)
    return bool(runs) and all(r["status"] == "PASS" for r in runs)


def _limitation_phrase(cases: list[str], limitations: list[str]) -> str:
    noun = "case" if len(cases) == 1 else "cases"
    documented = cases and all(c[:2] in limitations for c in cases)
    verb = "is" if len(cases) == 1 else "are"
    return f"{noun} {_num(cases)}" + (f", which {verb} a documented limitation," if documented else "")


def summary_sentence(headline: dict, final: dict | None = None, limitations: list[str] | None = None) -> str:
    """One plain-language sentence for the top of the README, from the raw files only."""
    limitations = limitations or []
    cases = list(dict.fromkeys(r["case"] for r in headline["results"]))
    p, n = _passed(headline["results"])
    text = f"On the first full eval pass, {p} of the {n} scripted conversations passed"
    if final:
        fp, fn = _passed(final["results"])
        both = [c for c in cases if not _ok([headline], c) and _by_case([final], c) and not _ok([final], c)]
        text += f"; the latest full pass {'also ' if (fp, fn) == (p, n) else ''}scored {fp}/{fn}"
        if both:
            text += f", and {_limitation_phrase(both, limitations)} failed in both"
    else:
        failed = [c for c in cases if not _ok([headline], c)]
        if failed:
            phrase = _limitation_phrase(failed, limitations).rstrip(",")
            text += f"; the {'failure was' if len(failed) == 1 else 'failures were'} {phrase}"
    return text + "."


def section(headline: dict, followups: list[dict], final: dict | None = None, final_pending: str | None = None,
            note: str | None = None, later: list[dict] | None = None, limitations: list[str] | None = None) -> str:
    """The EVAL-RESULTS block: plain-language result, then the table, then a link to the full report."""
    limitations = limitations or []
    cases = list(dict.fromkeys(r["case"] for r in headline["results"]))
    p, n = _passed(headline["results"])
    lead = [f"On the first full pass, {p} of the {n} scripted conversations passed (1 run per case)."]
    if final:
        fp, fn = _passed(final["results"])
        ran = [c for c in cases if _by_case([final], c)]
        fixed = [c for c in ran if not _ok([headline], c) and _ok([final], c)]
        new_fail = [c for c in ran if _ok([headline], c) and not _ok([final], c)]
        still = [c for c in ran if not _ok([headline], c) and not _ok([final], c)]
        parts = []
        if fixed:
            parts.append(f"{_num(fixed)} now pass{'es' if len(fixed) == 1 else ''}")
        if new_fail:
            healed = [c for c in new_fail if later and _ok(later, c)]
            who = (("it" if len(healed) == 1 else "both" if len(healed) == 2 else "all")
                   if healed == new_fail else _num(healed))
            parts.append(f"{_num(new_fail)} newly failed" + (f" ({who} passed again on a re-run after fixes)"
                                                              if healed else ""))
        if still:
            parts.append(f"{_limitation_phrase(still, limitations)} still fails" if len(still) == 1
                         else f"{_limitation_phrase(still, limitations)} still fail")
        done = "" if final.get("complete", True) else " so far (pass not complete)"
        lead.append(f"The latest full pass scored {fp}/{fn}{done}" + (f": {'; '.join(parts)}." if parts else "."))
    elif final_pending:
        lead.append("A newer full pass is running and is not in the table yet.")
    if note:
        lead.append(note.strip())
    lead.append("The first pass stays the headline; later runs are shown beside it.")

    cols = [f"Headline {_commits([headline])}"]
    if followups:
        cols.append(f"After fix {_commits(followups)}")
    if final:
        cols.append(f"Full pass {_commits([final])}")
    elif final_pending:
        cols.append(f"Full pass `{final_pending}`")
    if later:
        cols.append(f"Re-run {_commits(later)}")
    lines = [" ".join(lead), "", "| Case | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
    for c in cases:
        row = [_cell(_by_case([headline], c))]
        if followups:
            row.append(_cell(_by_case(followups, c)))
        if final:
            row.append(_cell(_by_case([final], c)))
        elif final_pending:
            row.append("running")
        if later:
            row.append(_cell(_by_case(later, c)))
        lines.append(f"| {c} | " + " | ".join(row) + " |")
    lines += ["", f"`{NOT_RUN}` = not re-run. Full report, with per-check pass rates, what changed between commits, the "
                  "reasoning_effort of each run and its footnote, and failure details: [evals/results.md](evals/results.md)."]
    return "\n".join(lines)


def _code_commits_since(sha: str) -> int:
    """Commits after `sha` that changed the agent code (app/)."""
    out = subprocess.run(["git", "rev-list", "--count", f"{sha}..HEAD", "--", "app"], cwd=ROOT, capture_output=True,
                         text=True)
    return int(out.stdout.strip()) if out.returncode == 0 and out.stdout.strip().isdigit() else 0


def latency(raw: dict, label: str = "full eval pass") -> str:
    """The LATENCY block: model time per turn from one pass's recorded turn timings."""
    timings = [t for r in raw["results"] if r["status"] in ("PASS", "FAIL") for t in r["turn_timings"]]
    if not timings:
        return "No completed turns in the raw file, so no latency numbers."
    llm = [t["llm_ms"] for t in timings]
    calls = sum(t["llm_calls"] for t in timings)
    efforts = sorted({r.get("reasoning_effort") or UNKNOWN for r in raw["results"]})
    sha = (raw["results"][0].get("commit") or UNKNOWN)
    lines = [f"Measured on the {label} on `{sha[:7]}` (text mode, {len(timings)} turns, {calls} LLM calls, "
             f"`reasoning_effort` {', '.join(efforts)}):", "",
             "| Model time | p50 | p95 |", "|---|---|---|",
             f"| Per turn (all of the turn's LLM calls) | {pct(llm, .5) / 1000:.1f} s | {pct(llm, .95) / 1000:.1f} s |", "",
             f"That is {calls / len(timings):.1f} LLM calls per turn on average, about {sum(llm) / calls / 1000:.1f} s of "
             f"model time per call (mean). Turn totals from the free-tier eval are not reported as latency: they include "
             f"client-side quota-pacing sleeps (a median of about {pct([t.get('wait_ms', 0) for t in timings], .5) / 1000:.0f} s "
             f"per turn), which is waiting for Groq's token-per-minute cap, not model or agent time. There is no separate "
             f"before/after benchmark."]
    if sha != UNKNOWN and _code_commits_since(sha):
        lines[-1] += (f" The agent code has changed since this pass (see the re-run column in the eval table), so these "
                      f"numbers describe `{sha[:7]}`, not the latest commit.")
    return "\n".join(lines)


def fill(readme: str, content: str, name: str = "EVAL-RESULTS") -> str:
    """Replace everything between the NAME markers (the START marker's own note is rewritten too)."""
    start, end = f"<!-- {name}:START", f"<!-- {name}:END -->"
    pattern = re.compile(re.escape(start) + r"[^\n]*\n.*?" + re.escape(end), re.S)
    if not pattern.search(readme):
        raise SystemExit(f"{name} markers not found in README.md")
    return pattern.sub(lambda _: f"{start} — {MARK_NOTE} -->\n{content}\n{end}", readme)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--headline", required=True, help="raw file of the first full pass")
    ap.add_argument("--followups", nargs="*", default=[], help="raw files of after-fix re-runs, oldest first")
    ap.add_argument("--final", help="raw file of the latest full pass")
    ap.add_argument("--final-pending", metavar="SHA", help="a newer full pass is still running on this commit")
    ap.add_argument("--later", nargs="*", default=[], help="raw files of re-runs made after the latest full pass")
    ap.add_argument("--limitations", nargs="*", default=[], help="case numbers that are documented known limitations")
    ap.add_argument("--note", help="optional extra sentence for the eval block")
    args = ap.parse_args()
    if args.final and args.final_pending:
        raise SystemExit("use --final or --final-pending, not both")
    load = lambda p: load_raw(Path(p))
    head, final = load(args.headline), load(args.final) if args.final else None
    later = [load(p) for p in args.later]
    readme_path = ROOT / "README.md"
    readme = readme_path.read_text(encoding="utf-8")
    readme = fill(readme, summary_sentence(head, final, args.limitations), "EVAL-SUMMARY")
    readme = fill(readme, section(head, [load(p) for p in args.followups], final, args.final_pending, args.note,
                                  later, args.limitations), "EVAL-RESULTS")
    readme = fill(readme, latency(final) if final else latency(head, "first full eval pass"), "LATENCY")
    readme_path.write_text(readme, encoding="utf-8", newline="\n")
    print("README.md generated blocks updated: EVAL-SUMMARY, EVAL-RESULTS, LATENCY")


if __name__ == "__main__":
    main()
